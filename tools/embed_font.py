#!/usr/bin/env python3
"""TTF を C++ のバイト配列ソースへ埋め込む（生成専用・ビルド時に走る）。

usage: embed_font.py <sym> <font.ttf> [<sym> <font.ttf> ...] <out.inc>
"""
import sys


def emit(f, name, data):
    f.write(f"static const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 16):
        f.write("    " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
    f.write(f"static const unsigned int {name}Size = {len(data)}u;\n")


def main():
    args = sys.argv[1:]
    if len(args) < 3 or len(args) % 2 != 1:
        sys.stderr.write(__doc__)
        return 2
    out = args[-1]
    pairs = args[:-1]
    with open(out, "w") as f:
        f.write("// generated by tools/embed_font.py — do not edit\n")
        for i in range(0, len(pairs), 2):
            with open(pairs[i + 1], "rb") as g:
                emit(f, pairs[i], g.read())
    return 0


if __name__ == "__main__":
    sys.exit(main())
