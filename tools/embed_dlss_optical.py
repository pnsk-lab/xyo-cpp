#!/usr/bin/env python3
"""Embed the Vulkan optical-flow motion-vector conversion compute shader.

Requires glslangValidator. Regeneration is optional at normal build time:
the generated header is checked in alongside the shader source.
"""
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/render/shaders/dlss_optical_vectors.comp"
OUTPUT = ROOT / "src/render/dlss_optical_vectors_embedded.hpp"


def main() -> None:
    with tempfile.TemporaryDirectory() as temp:
        binary = Path(temp) / "motion.spv"
        subprocess.run(
            ["glslangValidator", "-V", "-S", "comp", str(SOURCE),
             "-o", str(binary)],
            check=True,
        )
        data = binary.read_bytes()
    if len(data) % 4:
        raise ValueError("SPIR-V size must be multiple of 4")
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines = [
        "// Generated by tools/embed_dlss_optical.py. Do not edit by hand.",
        "#pragma once",
        "#include <cstdint>",
        "namespace xyo::render {",
        "inline constexpr uint32_t kDlssOpticalVectorsSpv[] = {",
    ]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + ",")
    lines += ["};", "} // namespace xyo::render", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"{OUTPUT.relative_to(ROOT)}: {len(data)} bytes")


if __name__ == "__main__":
    main()
