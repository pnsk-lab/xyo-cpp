#!/usr/bin/env python3
"""Embed GLSL compute shader for opt-in NGX current-color bias mask."""
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/render/shaders/dlss_bias_mask.comp"
OUTPUT = ROOT / "src/render/dlss_bias_mask_embedded.hpp"

with tempfile.TemporaryDirectory() as temp:
    binary = Path(temp) / "bias.spv"
    subprocess.run(["glslangValidator", "-V", "-S", "comp",
                    str(SOURCE), "-o", str(binary)], check=True)
    data = binary.read_bytes()
words = struct.unpack(f"<{len(data)//4}I", data)
lines = [
    "// Generated by tools/embed_dlss_bias_mask.py; do not edit.",
    "#pragma once",
    "#include <cstdint>",
    "namespace xyo::render {",
    "inline constexpr uint32_t kDlssBiasMaskSpv[] = {",
]
for i in range(0,len(words),8):
    lines.append("    "+", ".join(f"0x{x:08x}" for x in words[i:i+8])+",")
lines += ["};","} // namespace xyo::render",""]
OUTPUT.write_text("\n".join(lines))
print(f"{OUTPUT.relative_to(ROOT)}: {len(data)} bytes")
