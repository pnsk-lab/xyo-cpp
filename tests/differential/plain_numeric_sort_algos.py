#!/usr/bin/env python3
"""Sorting parity on independently generated Scratch projects.

The original Scratch algorithm bodies are generated by gen_algo_bench.py.
Wall-clock and millisecond timer values are deliberately excluded from parity.
"""
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "tests/bench/algos/gen_algo_bench.py"
CASES = (("bubblesort", 100), ("quicksort", 500), ("mergesort", 500))


def project_state(binary: Path, sb3: Path, tier: str, mode: str):
    assert mode in ("off", "integer", "ordered")
    env = {key: value for key, value in os.environ.items()
           if not key.startswith("XYO_")}
    env.update({
        "XYO_DUMPVARS": "json",
        "XYO_JIT_PLAIN_NUMBER_CMP": "0" if mode == "off" else "1",
        "XYO_JIT_FP_ORDERED_CMP": "1" if mode == "ordered" else "0",
        "XYO_GPU": "0", "XYO_PARFOR": "0", "XYO_PAR": "0",
    })
    command = [str(binary), "run", str(sb3), "--jit", tier,
               "--frames", "600"]
    result = subprocess.run(command, cwd=ROOT, env=env, text=True,
                            capture_output=True, timeout=60)
    if result.returncode:
        raise RuntimeError(
            f"{sb3.name} {tier} mode={mode}: "
            f"{result.stderr[-800:]}")
    text = result.stdout
    try:
        bench = json.loads(text[text.index("{"):text.rindex("}") + 1])["Bench"]
    except (ValueError, KeyError) as error:
        raise RuntimeError(f"Missing Bench state: {text[-800:]}") from error
    if bench["ok"] != "1":
        raise AssertionError((sb3.name, tier, mode, bench["check"]))
    return bench["check"], bench["data"]


def main():
    binary = (Path(sys.argv[1]) if len(sys.argv) > 1
              else ROOT / "build/xyo").resolve()
    outdir = ROOT / "build/plain-number-sort-algos"
    outdir.mkdir(parents=True, exist_ok=True)
    for name, n in CASES:
        subprocess.run([
            sys.executable, str(GENERATOR), str(outdir), "--only", name,
            "--sizes", f"{name}={n}",
        ], cwd=ROOT, check=True, capture_output=True, text=True)
        sb3 = outdir / f"{name}_{n}.sb3"
        reference = None
        for tier in ("off", "eager", "hotspot"):
            for mode in ("off", "integer", "ordered"):
                state = project_state(binary, sb3, tier, mode)
                if reference is None:
                    reference = state
                elif state != reference:
                    raise AssertionError(
                        (name, tier, mode, reference[0], state[0]))
                print(f"{name}/{n} {tier} mode={mode}: "
                      f"PASS checksum={state[0]}", flush=True)


if __name__ == "__main__":
    main()
